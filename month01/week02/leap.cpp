// Week 2 · Day 8（原定 9/24）任务：逻辑运算 && || ! —— 闰年判断
//
//   今天只有一件事：让程序「同时满足好几个条件」才做某件事。
//
//   闰年的官方规矩（背下来，考试和面试都会问）：
//     能被 4 整除，并且 不能被 100 整除   →  是闰年
//     或者 能被 400 整除                  →  也是闰年
//
//   几个符号：
//     &&   并且   —— 两边都真才真
//     ||   或者   —— 有一边真就真
//     !    非     —— 真变假，假变真
//     %    取余   —— 5 % 2 得 1；整除时得 0（Day3 你用过它）
//     !=   不等于 —— 和 == 相反
//
//   用法示例：
//     if (a > 0 && b > 0)        // a 和 b 都是正数
//     if (a == 0 || b == 0)      // 至少有一个是 0
//
//   验收：这四个年份的结果必须全对
//     2024 → 是闰年
//     2025 → 不是闰年
//     1900 → 不是闰年    ← 能被 4 整除却不是闰年，这个最容易错
//     2000 → 是闰年      ← 能被 100 整除却是闰年，这个也容易错
//
//   ★ 提前告诉你的四个坑：
//     1. 判断相等是两个等号 ==。一个等号 = 是「赋值」。
//        写成 if (year = 4) 编译器不报错，但条件永远为真 —— 这种静默的错最难查。
//     2. && 和 || 的优先级比 == 低，条件一长就老老实实加括号。今天这句最稳的写法：
//          if ((year % 4 == 0 && year % 100 != 0) || year % 400 == 0)
//     3. % 只能用在整数上，别拿 double 去取余。
//     4. if (...) 后面千万不要加分号 —— 分号会被当成「空的一步」。
//        Day6 的 for 循环你踩过一模一样的坑，而且它同样不报错。
//
//   加分题（可选）：用 ! 把逻辑反过来写一遍，判断「不是闰年」。

#include <iostream>
#include<windows.h>

int main() {
    SetConsoleOutputCP(65001);

    int year = 0;
    std::cout << "请输入年份：";
    std::cin >> year;

    // ★ 今天唯一要你写的地方：把 false 换成真正的判断式
    //    提示：先用 % 和 == 拼出「能被 4 整除 且 不能被 100 整除」，再用 || 接上「能被 400 整除」
    bool isLeap = false;

    if (isLeap) {
        std::cout << year << " 是闰年\n";
    } else {
        std::cout << year << " 不是闰年\n";
    }

    return 0;
}