#include <iostream>
#include<windows.h>
int main() {
    SetConsoleOutputCP(65001);
    // 你的代码从这里开始写
    double c;
    std::cout << "请输入摄氏温度\n";
    std::cin >> c;
    c = c * 9 / 5 + 32;
    std::cout << c << "\n";
    return 0;
}