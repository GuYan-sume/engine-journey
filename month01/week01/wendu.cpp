// ─────────────────────────────────────────────────────────────
// Day 4（9/18）任务：学会 if 判断
//   要求：输入的温度如果「低于 0 度」，额外打印一行「结冰」
//   验收：输入 100 -> 212        （不打印结冰）
//         输入  -5 -> 23 结冰     （要打印结冰）
//         输入   0 -> 32          （0 不算，条件是「低于」0）
//
//   今天会碰到的词：if、条件、大括号代码块、比较运算符 < > <= >= == !=
//   坑：程序里的「等于」要写两个 =（==），一个 = 是赋值 —— 新手最常见的错
//   提示：换算那一行会把 c 覆盖成华氏度，所以判断要写在它前面；
//         或者新开一个变量存华氏度：double f = c * 9 / 5 + 32;


// ─────────────────────────────────────────────────────────────
// Day 5（9/19）任务：学会 else / else if（分情况）
//   要求：把温度分成三档，先打印档位，再打印华氏度
//         c < 0      -> 结冰
//         0 <= c <= 100 -> 常温
//         c > 100    -> 沸腾
//   验收：输入 -5  -> 结冰 / 23
//         输入  0  -> 常温 / 32
//         输入 25  -> 常温 / 77
//         输入 100 -> 常温 / 212
//         输入 120 -> 沸腾 / 248
//
//   骨架（把 XXX 换成你自己的写法，注意分支的先后顺序）:
//     if (c < 0) {
//         XXX
//     } else if (c <= 100) {
//         XXX
//     } else {
//         XXX
//     }
//
//   陷阱实验（做完必做）：把 else if 和 else 两段的顺序对调，再输入 -5，
//   看它会不会说「常温」—— 想明白为什么，今天就算过了。
//   提示：整段判断仍然要写在 c 被换算成华氏度之前。


// ─────────────────────────────────────────────────────────────
// Day 5 下半场（9/19）任务：学会 while 循环 —— 让程序不用跑一次就退出
//   要求：
//     1) 反复提示「请输入摄氏温度」，每算完一个接着问下一个
//     2) 输入 -999 时打印「再见」并退出（-999 是暗号，用来结束程序）
//     3) 原来的三档判断 + 华氏换算照旧保留
//   验收：
//     输入  -5  -> 结冰 / 23    （然后继续问，不退出）
//     输入  25  -> 常温 / 77    （然后继续问）
//     输入 120  -> 沸腾 / 248   （然后继续问）
//     输入 -999 -> 再见         （程序结束）
//
//   今天会碰到的词：while、循环体、转一圈叫「一次迭代」、break（跳出循环）、无限循环
//   骨架（大括号要包住「从提问到输出」的整段）:
//     while (true) {
//         std::cout << "请输入摄氏温度（输入 -999 退出）：\n";
//         double c;
//         std::cin >> c;
//         if (c == -999) {
//             std::cout << "再见\n";
//             break;
//         }
//         XXX   <- 把原来的三档判断 + 换算 + 输出整段搬进来
//     }
//
//   提醒：while (true) 的意思是「永远转下去」，所以必须靠 break 才能停下；
//         万一写出停不下来的循环，在黑窗口里按 Ctrl+C 强停，程序不会坏。
//   提示：循环体里写的 double c; 每一圈都会重新来一次，所以不用手动清零。

#include <iostream>
#include<windows.h>
int main() {
    SetConsoleOutputCP(65001);
    while (true) {
            // 你的代码从这里开始写
            double c;
            std::cout << "请输入摄氏温度\n";
            std::cin >> c;
            if (c == -999) {
                std::cout << "再见\n";
                break;
            }
            if (c < 0) {
                std::cout << "结冰\n";
            }
            else if (c <= 100) {
                std::cout << "常温\n";
            }
            else {
                std::cout << "沸腾\n";
            }
            c = c * 9 / 5 + 32;
            std::cout << c << "\n";
        }
    return 0;
}