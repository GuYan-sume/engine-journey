// 任务：读入一个「摄氏温度」，换算成「华氏温度」并打印出来。
//   公式：华氏 = 摄氏 × 9 ÷ 5 + 32
//   验收：输入 100  ->  输出 212
//         输入  37  ->  输出 98.6
//
// 今天会碰到的词（不懂就去查 第一章-2-名词与符号词典.md）：
//   变量、类型（int / double）、std::cin、算术运算与优先级、整数除法
//
// 提示：先用 int 存温度试试。如果你算出来是 98 而不是 98.6 —— 别急着改，
//       先想清楚差在哪，那正是今天最重要的一课。

// ─────────────────────────────────────────────────────────────
// Day 4（9/18）任务：学会 if 判断
//   要求：输入的温度如果「低于 0 度」，额外打印一行「结冰」
//   验收：输入 100 -> 212        （不打印结冰）
//         输入  -5 -> 23 结冰     （要打印结冰）
//         输入   0 -> 32          （0 不算，条件是「低于」0）
//
//   今天会碰到的词：if、条件、大括号代码块、比较运算符 < > <= >= == !=
//   坑：程序里的「等于」要写两个 =（==），一个 = 是赋值 —— 新手最常见的错
//   提示：换算那一行会把 c 覆盖成华氏度，所以判断要写在它前面；
//         或者新开一个变量存华氏度：double f = c * 9 / 5 + 32;

#include <iostream>
#include<windows.h>
int main() {
    SetConsoleOutputCP(65001);
    // 你的代码从这里开始写
    double c;
    std::cout << "请输入摄氏温度\n";
    std::cin >> c;
    if (c < 0) {
        std::cout << "结冰\n";
    }
    c = c * 9 / 5 + 32;
    std::cout << c << "\n";
    return 0;
}