//   公式：华氏 = 摄氏 × 9 ÷ 5 + 32
//   验收：输入 100  ->  输出 212
//         输入  37  ->  输出 98.6
//
// 今天会碰到的词（不懂就去查 第一章-2-名词与符号词典.md）：
